# GENERATOR: writes RobotoUiFontOutlineData.kt into awake/core/text.
# Kinds are defined in tools/README.md. Only a GATE can fail a build; visual tooling tests cover
# the helper itself.
"""Embeds the outlines and pair kerning of the built-in atlas's glyphs, for every Roboto weight, in awake:core:text.

The atlases ship distance fields. Small text draws instead from glyphs rasterized at the exact pixel
size (PixelGlyphs), which needs the outlines themselves. Each weight is subset to the atlas's own
characters (UiFonts.DEFAULT_CHARS) with no hinting or naming tables, about 12 KB a face, and written as
base64 for OpenTypeFont to read at run time.

The subset keeps glyf, loca, cmap, hmtx, hhea, head and maxp, exactly as the source face has them, so a
glyph's outline and advance are the source's. RobotoOutlinesTest, in awake:core:text, is the gate: it
reads every character from this data and from the full face and fails on any difference.

It also keeps GPOS with only the `kern` feature's pair positioning lookups, subset to the same glyphs,
which is where the face's kerning lives (Roboto has no `kern` table); KerningPairs reads it when the
built-in font lays text out. RobotoKerningTest is its gate: every pair of atlas characters must kern by
the same amount in this data as in the full face.

Timestamps are kept, so a re-run writes the same bytes.

Usage:
    python3 tools/fonts-tooling/subset_roboto_outlines.py
"""

from __future__ import annotations

import base64
import io
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

REPO = Path(__file__).resolve().parent.parent.parent
FONT_DIR = REPO / "awake/ui/font-atlas-generator/fonts"
OUT = REPO / "awake/core/text/src/commonMain/kotlin/com/awakekt/awake/core/text/font/RobotoUiFontOutlineData.kt"

# UiFonts.DEFAULT_CHARS: printable ASCII, then the atlas's extra punctuation, in atlas order.
CHARS = "".join(chr(code) for code in range(32, 127)) + "•·…–—×−"

FACES = [
    ("Roboto-Thin.ttf", "THIN"),
    ("Roboto-Light.ttf", "LIGHT"),
    ("Roboto-Regular.ttf", "REGULAR"),
    ("Roboto-Medium.ttf", "MEDIUM"),
    ("Roboto-SemiBold.ttf", "SEMI_BOLD"),
    ("Roboto-Bold.ttf", "BOLD"),
    ("Roboto-Black.ttf", "BLACK"),
]

LINE_WIDTH = 120

HEADER = """/*
 * SPDX-FileCopyrightText: 2023-2026 Ron June Valdoz
 *
 * SPDX-License-Identifier: Apache-2.0
 */
@file:Suppress("LargeClass")

package com.awakekt.awake.core.text.font

"""

# REUSE-IgnoreStart
SNIPPET_BEGIN = """// SPDX-SnippetBegin
// SPDX-SnippetCopyrightText: 2011 The Roboto Project Authors (https://github.com/googlefonts/roboto-classic)
// SPDX-License-Identifier: OFL-1.1

"""
SNIPPET_END = "// SPDX-SnippetEnd\n"
# REUSE-IgnoreEnd


def subset_face(path: Path) -> bytes:
    options = subset.Options()
    # Pair kerning only: `cpsp` and the mark features are not applied by default, and GSUB is shaping (#852).
    options.layout_features = ["kern"]
    options.hinting = False
    options.notdef_outline = True
    options.drop_tables += ["GDEF", "GSUB", "STAT", "gasp", "DSIG", "name", "post", "OS/2"]
    font = TTFont(path, recalcTimestamp=False)
    subsetter = subset.Subsetter(options)
    subsetter.populate(text=CHARS)
    subsetter.subset(font)
    out = io.BytesIO()
    font.save(out)
    return out.getvalue()


def kotlin_string(name: str, data: bytes) -> str:
    encoded = base64.b64encode(data).decode("ascii")
    lines = [encoded[i : i + LINE_WIDTH] for i in range(0, len(encoded), LINE_WIDTH)]
    body = "\n".join(f"        {line}" for line in lines)
    return f'    const val {name}: String = """\n{body}\n    """\n'


def main() -> int:
    parts = []
    for file_name, constant in FACES:
        data = subset_face(FONT_DIR / file_name)
        parts.append(kotlin_string(constant, data))
        print(f"{file_name:22} {len(data):>7,} bytes")
    source = (
        HEADER
        + SNIPPET_BEGIN
        + "/**\n"
        + " * Generated by `tools/fonts-tooling/subset_roboto_outlines.py` -- do not hand-edit. Each weight of the\n"
        + " * built-in Roboto, subset to the atlas's characters with no hinting and only the `kern` feature's\n"
        + " * GPOS lookups, as base64 TrueType; see [RobotoOutlines].\n"
        + " */\n"
        + "internal object RobotoUiFontOutlineData {\n"
        + "\n".join(parts)
        + "}\n"
        + SNIPPET_END
    )
    OUT.write_text(source, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
