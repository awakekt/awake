// Mocha's timeout for every wasmJs browser test, set once. Mocha's 2 s default applies to synchronous
// tests too, so a test that finished and printed its result was still marked failed, with "Timeout of
// 2000ms exceeded" or a bare "Error", whenever it ran past 2 s on a shared runner (#1521, #1717).
// Seven modules had grown their own karma.config.d copy of this setting before it lived here (#1592).
//
// The timeout guards against a hang; it is not a performance assertion. A test that measures time
// asserts on its own figure.
//
// Kotlin's Karma DSL has no Mocha setting, so this writes a karma.config.d snippet before the browser
// tests run, as com.awakekt.awake.plugin.test-resources does. The snippet is generated and gitignored.
// The library and application conventions apply this plugin; a module on neither applies it itself.
//
// It also sets what a browser test run logs. CI keeps only the log for most browser tests, and many of
// them print the figure they assert on (a frame's heap, a poll's bytes). So each test is named as it
// passes, its output is shown, and a failure prints its assertion in full: a run proves which tests ran
// and keeps their numbers. Five modules had their own copy of this block, and a module without one
// ran its tests in silence (#1512).

val mochaTimeoutMillis = 120_000
// Karma's default browserNoActivityTimeout is 30 s — shorter than mochaTimeoutMillis — so slow
// synchronous heap/WebGPU browser tests on shared CI runners can disconnect before finishing even
// though Mocha still allows them to run. Keep Karma's inactivity window above Mocha's timeout.
val karmaBrowserNoActivityTimeoutMillis = 180_000
val karmaBrowserDisconnectTimeoutMillis = 60_000

val mochaTimeoutSnippet = layout.projectDirectory.file("karma.config.d/awake-mocha-timeout.js")

val generateAwakeKarmaMochaTimeout = tasks.register("generateAwakeKarmaMochaTimeout") {
    description = "Writes the shared Mocha and Karma inactivity timeouts into karma.config.d for the wasmJs browser tests."
    inputs.property("timeout", mochaTimeoutMillis)
    inputs.property("browserNoActivityTimeout", karmaBrowserNoActivityTimeoutMillis)
    inputs.property("browserDisconnectTimeout", karmaBrowserDisconnectTimeoutMillis)
    outputs.file(mochaTimeoutSnippet)
    doLast {
        val file = mochaTimeoutSnippet.asFile
        file.parentFile.mkdirs()
        file.writeText(
            "// Generated by com.awakekt.awake.plugin.browser-tests -- do not edit, gitignored.\n" +
                "config.client = config.client || {};\n" +
                "config.client.mocha = Object.assign({}, config.client.mocha, { timeout: $mochaTimeoutMillis });\n" +
                "config.browserNoActivityTimeout = Math.max(config.browserNoActivityTimeout || 0, $karmaBrowserNoActivityTimeoutMillis);\n" +
                "config.browserDisconnectTimeout = Math.max(config.browserDisconnectTimeout || 0, $karmaBrowserDisconnectTimeoutMillis);\n",
        )
    }
}

tasks.matching { it.name == "wasmJsBrowserTest" }.configureEach {
    dependsOn(generateAwakeKarmaMochaTimeout)
}

tasks.withType<AbstractTestTask>().matching { it.name == "wasmJsBrowserTest" }.configureEach {
    testLogging {
        events("passed", "skipped", "failed")
        showStandardStreams = true
        showExceptions = true
        exceptionFormat = org.gradle.api.tasks.testing.logging.TestExceptionFormat.FULL
    }
}
