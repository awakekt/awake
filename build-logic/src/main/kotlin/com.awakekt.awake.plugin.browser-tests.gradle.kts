// Mocha's timeout for every wasmJs browser test, set once. Mocha's 2 s default applies to synchronous
// tests too, so a test that finished and printed its result was still marked failed, with "Timeout of
// 2000ms exceeded" or a bare "Error", whenever it ran past 2 s on a shared runner (#1521, #1717).
// Seven modules had grown their own karma.config.d copy of this setting before it lived here (#1592).
//
// The timeout guards against a hang; it is not a performance assertion. A test that measures time
// asserts on its own figure.
//
// Kotlin's Karma DSL has no Mocha setting, so this writes a karma.config.d snippet before the browser
// tests run, as com.awakekt.awake.plugin.test-resources does. The snippet is generated and gitignored.
// The library and application conventions apply this plugin; a module on neither applies it itself.

val mochaTimeoutMillis = 120_000

val mochaTimeoutSnippet = layout.projectDirectory.file("karma.config.d/awake-mocha-timeout.js")

val generateAwakeKarmaMochaTimeout = tasks.register("generateAwakeKarmaMochaTimeout") {
    description = "Writes the shared Mocha timeout into karma.config.d for the wasmJs browser tests."
    inputs.property("timeout", mochaTimeoutMillis)
    outputs.file(mochaTimeoutSnippet)
    doLast {
        val file = mochaTimeoutSnippet.asFile
        file.parentFile.mkdirs()
        file.writeText(
            "// Generated by com.awakekt.awake.plugin.browser-tests -- do not edit, gitignored.\n" +
                "config.client = config.client || {};\n" +
                "config.client.mocha = Object.assign({}, config.client.mocha, { timeout: $mochaTimeoutMillis });\n",
        )
    }
}

tasks.matching { it.name == "wasmJsBrowserTest" }.configureEach {
    dependsOn(generateAwakeKarmaMochaTimeout)
}
