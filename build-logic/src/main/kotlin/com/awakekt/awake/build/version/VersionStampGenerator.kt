package com.awakekt.awake.build.version

import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.TypeSpec

/** What [shortCommit] answers outside a git checkout, or where git is missing. */
const val UNKNOWN_COMMIT = "unknown"

/**
 * The Kotlin source for an `object` [objectName] in [packageName] with `const val VERSION` and
 * `const val COMMIT`, so an app or library can report what it was built from.
 *
 * [version] must be a [ReleaseVersion]; a build stamping `1.0` fails rather than shipping it.
 */
fun generateVersionStamp(
    version: String,
    commit: String,
    packageName: String,
    objectName: String = "VersionStamp",
): String {
    val parsed = ReleaseVersion.parse(version)
    val stamp = TypeSpec.objectBuilder(objectName).addModifiers(KModifier.PUBLIC)
        .addKdoc("What this build was made from. Generated; do not edit.\n")
        .addProperty(constant("VERSION", parsed.toString(), "The release version, such as 1.2.0 or 1.2.0-rc.1."))
        .addProperty(constant("COMMIT", commit.ifBlank { UNKNOWN_COMMIT }, "The short git commit, or \"unknown\"."))
        .build()
    return FileSpec.builder(packageName, objectName)
        .addFileComment("Generated by the Awake version-stamp plugin. Do not edit.")
        .addType(stamp)
        .build()
        .toString()
}

private fun constant(name: String, value: String, doc: String): PropertySpec =
    PropertySpec.builder(name, String::class).addModifiers(KModifier.PUBLIC, KModifier.CONST)
        .addKdoc("%L\n", doc).initializer("%S", value).build()
