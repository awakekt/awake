package com.awakekt.awake.build.strings

import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.TypeSpec

/**
 * The Kotlin source for a typed view of [table]: a `value class` [keyTypeName] holding the key string,
 * and an `object` [objectName] whose members are those keys, nested by dotted path, so code reads
 * `Strings.menu.start` and no raw string. Both go in one file in [packageName], and nothing outside the
 * Kotlin standard library is referenced.
 *
 * Every declaration is `public` explicitly, so the file compiles under explicit API mode.
 */
fun generateStringKeys(
    table: StringTable,
    packageName: String,
    objectName: String = "Strings",
    keyTypeName: String = "StringKey",
): String {
    val tree = KeyTree.build(table, reserved = setOf(keyTypeName))
    val keyType = ClassName(packageName, keyTypeName)
    val holder = TypeSpec.objectBuilder(objectName).addModifiers(KModifier.PUBLIC)
        .addKdoc("Typed keys of the string table. Generated; do not edit.\n")
    fill(holder, tree, keyType)
    return FileSpec.builder(packageName, objectName)
        .addFileComment("Generated by the Awake string-keys plugin. Do not edit.")
        .addType(keyTypeSpec(keyTypeName))
        .addType(holder.build())
        .build()
        .toString()
}

private fun keyTypeSpec(name: String): TypeSpec = TypeSpec.classBuilder(name)
    .addModifiers(KModifier.PUBLIC, KModifier.VALUE)
    .addAnnotation(ClassName("kotlin.jvm", "JvmInline"))
    .addKdoc("A key into the string table; [key] is the dotted path as written in the table.\n")
    .primaryConstructor(FunSpec.constructorBuilder().addParameter("key", String::class).build())
    .addProperty(PropertySpec.builder("key", String::class).initializer("key").build())
    .addFunction(FunSpec.builder("toString").addModifiers(KModifier.OVERRIDE).returns(String::class)
        .addStatement("return key").build())
    .build()

private fun fill(into: TypeSpec.Builder, tree: KeyTree, keyType: ClassName) {
    for ((name, entry) in tree.leaves) {
        into.addProperty(
            PropertySpec.builder(name, keyType).addModifiers(KModifier.PUBLIC)
                .addKdoc("%L\n", docText(entry.value))
                .initializer("%T(%S)", keyType, entry.path.raw)
                .build(),
        )
    }
    for ((name, group) in tree.groups) {
        val nested = TypeSpec.objectBuilder(name).addModifiers(KModifier.PUBLIC)
        fill(nested, group, keyType)
        into.addType(nested.build())
    }
}

/** The value as one KDoc line: a comment terminator would end the comment early. */
private fun docText(value: String): String =
    value.replace("*/", "* /").replace("/*", "/ *").replace(Regex("\\s+"), " ").trim().take(120)
