package com.awakekt.awake.core.localization

import kotlin.math.abs
import kotlin.math.floor
import kotlin.math.log10

/** How [NumberFormat] writes a number. A message names it as `{n, number, <style>}`. */
enum class NumberStyle {
    /** Grouped, with up to three fraction digits: `1,234.5`. `{n, number}`. */
    Decimal,

    /** Grouped and rounded to a whole number: `1,235`. `{n, number, integer}`. */
    Integer,

    /** Times 100, rounded, with the locale's percent sign: `45%`, `45 %`, `%45`. `{n, number, percent}`. */
    Percent,

    /** Short, for a HUD: `1.2K`, `12K`, `1.2M`, `1,2 Mio.`, `1.2万`. `{n, number, compact}`. */
    Compact,
}

/**
 * Writes numbers the way a locale does: its decimal and grouping separators (`1,234.5`, `1.234,5`,
 * `1 234,5`), its percent pattern and its short compact forms.
 *
 * The data is Unicode CLDR's (version [CLDR_VERSION]), generated by the module's
 * `generateCldrNumberData` task for every language [PluralRules] covers; any other language gets
 * CLDR's root format, which writes `1,234.5`. Numbers round half to even, as ICU does, and use Latin digits.
 *
 * ```kotlin
 * NumberFormat.forLocale(LocaleId.of("de")).format(1234.5)                     // "1.234,5"
 * NumberFormat.forLocale(LocaleId.of("fr")).format(0.25, NumberStyle.Percent)  // "25 %"
 * NumberFormat.forLocale(LocaleId.English).format(12_345, NumberStyle.Compact) // "12K"
 * ```
 *
 * Some locales group with a no-break space (U+00A0 or U+202F) or put direction marks around a sign,
 * as CLDR says; a font that lacks them draws its stand-in glyph there.
 */
class NumberFormat private constructor(private val data: CldrNumbers, private val plurals: PluralRule) {

    /** Each compact row parsed when first used: category to pattern, or null for a size left uncompacted. */
    private val compactRows = arrayOfNulls<Map<PluralCategory, CompactPattern>?>(data.compact.size)
    private val compactParsed = BooleanArray(data.compact.size)

    /**
     * Writes [value] in [style].
     *
     * @param value An [Int], [Long], [Short], [Byte], [Double] or [Float]; any other [Number] is read
     *   as a [Double].
     * @param style How to write it.
     * @return The text.
     */
    fun format(value: Number, style: NumberStyle = NumberStyle.Decimal): String {
        val double = value.toDouble()
        val text = when {
            double.isNaN() -> "NaN"
            double.isInfinite() -> "∞"
            style == NumberStyle.Decimal -> decimal(value, DECIMAL_DIGITS)
            style == NumberStyle.Integer -> decimal(value, 0)
            style == NumberStyle.Percent -> data.percent.replace("0", decimal(abs(double) * PERCENT, 0))
            else -> compact(abs(double))
        }
        // A number that rounds to zero has no sign.
        val signed = double < 0 && (double.isInfinite() || text.any { it in '1'..'9' })
        return if (signed) data.minus + text else text
    }

    /** The absolute value of [value], grouped, with at most [maxFraction] fraction digits. */
    private fun decimal(value: Number, maxFraction: Int): String {
        val (whole, fraction) = if (value.isWhole()) {
            val long = value.toLong()
            (if (long == Long.MIN_VALUE) "9223372036854775808" else abs(long).toString()) to ""
        } else {
            rounded(abs(value.toDouble()), maxFraction)
        }
        return join(whole, fraction, data.minimumGrouping)
    }

    private fun join(whole: String, fraction: String, minimumGrouping: Int): String {
        val grouped = if (whole.length < GROUP + minimumGrouping) {
            whole
        } else {
            buildString {
                val first = whole.length % GROUP
                if (first > 0) append(whole, 0, first)
                var i = first
                while (i < whole.length) {
                    if (i > 0) append(data.group)
                    append(whole, i, i + GROUP)
                    i += GROUP
                }
            }
        }
        return if (fraction.isEmpty()) grouped else grouped + data.decimal + fraction
    }

    private fun compact(value: Double): String {
        val exponent = if (value < THOUSAND) 0 else floor(log10(value)).toInt().coerceAtMost(MAX_EXPONENT)
        var fit = if (exponent == 0) null else compactAt(value, exponent)
        // 999,999 rounds to 1000K, which is 1M.
        if (fit != null && fit.overflows && exponent < MAX_EXPONENT) fit = compactAt(value, exponent + 1) ?: fit
        if (fit == null) {
            // Too small to compact, or a size this locale leaves whole: two significant digits below 10.
            val (whole, fraction) = rounded(value, compactFraction(value))
            return join(whole, fraction, maxOf(COMPACT_GROUPING, data.minimumGrouping))
        }
        val (whole, fraction) = fit.digits
        val category = plurals.select(PluralOperands.of(if (fraction.isEmpty()) whole else "$whole.$fraction"))
        val pattern = fit.row[category] ?: fit.pattern
        return pattern.prefix + join(whole, fraction, COMPACT_GROUPING) + pattern.suffix
    }

    /** [value] in the compact row of [exponent], or null when the locale leaves that size whole. */
    private fun compactAt(value: Double, exponent: Int): Compacted? = compactRow(exponent)?.let { row ->
        row[PluralCategory.Other]?.let { pattern ->
            val scaled = value / tenTo(exponent - pattern.zeros + 1)
            Compacted(row, pattern, rounded(scaled, if (scaled < 10) 1 else 0))
        }
    }

    private fun compactRow(exponent: Int): Map<PluralCategory, CompactPattern>? {
        val index = exponent - FIRST_COMPACT_EXPONENT
        if (!compactParsed[index]) {
            compactRows[index] = parseCompactRow(data.compact[index])
            compactParsed[index] = true
        }
        return compactRows[index]
    }

    /** A compact pattern split around its run of zeros: `0 тыс.` is "", 1 zero, " тыс.". */
    private class CompactPattern(val prefix: String, val zeros: Int, val suffix: String)

    /** A number scaled into a compact row: its whole and fraction digits, and the row's `other` pattern. */
    private class Compacted(val row: Map<PluralCategory, CompactPattern>, val pattern: CompactPattern, val digits: Pair<String, String>) {
        /** Rounding carried it past the row's zeros, as 999.96 thousand rounds to 1000. */
        val overflows: Boolean get() = digits.first.length > pattern.zeros
    }

    companion object {
        /** The CLDR release the data comes from. */
        const val CLDR_VERSION: String = CldrNumberData.VERSION

        /** CLDR's root format, for a language with no data of its own: `1,234.5`, `45%`, `1.2K`. */
        val Root: NumberFormat = NumberFormat(CldrNumberData.locales.getValue("und"), PluralRules.Root)

        /**
         * The format [locale] writes numbers in: the most specific locale in its fallback chain that
         * has data, so `pt-PT` has its own and `pt-BR` uses `pt`'s.
         *
         * @param locale The locale.
         * @return The format, or [Root] for a language not covered.
         */
        fun forLocale(locale: LocaleId): NumberFormat {
            val chain = if (locale.language == "tl") LocaleId.of("fil").fallbackChain else locale.fallbackChain
            val data = chain.firstNotNullOfOrNull { CldrNumberData.locales[it.tag] } ?: return Root
            return NumberFormat(data, PluralRules.forLocale(locale))
        }

        private const val DECIMAL_DIGITS = 3
        private const val PERCENT = 100.0
        private const val GROUP = 3
        private const val THOUSAND = 1000.0
        private const val FIRST_COMPACT_EXPONENT = 3
        private const val MAX_EXPONENT = 14

        /** ICU groups compact numbers only from five digits, `12,345` but `1234`. */
        private const val COMPACT_GROUPING = 2

        /** Digits a double keeps exactly; past this its integer part is written from its shortest form. */
        private const val EXACT_LIMIT = 9.0e15
        private const val MAX_FRACTION = 6

        private fun Number.isWhole(): Boolean = this is Int || this is Long || this is Short || this is Byte

        /** Fraction digits for two significant digits below 10, none from 10: `5.7`, `57`, `0.57`. */
        private fun compactFraction(value: Double): Int = when {
            value >= 10 || value == 0.0 -> 0
            value >= 1 -> 1
            else -> (1 - floor(log10(value)).toInt()).coerceAtMost(MAX_FRACTION)
        }

        private fun tenTo(exponent: Int): Double {
            var result = 1.0
            repeat(exponent) { result *= 10 }
            return result
        }

        /** [value] ≥ 0 rounded half to even to [maxFraction] digits, as whole digits and fraction digits without trailing zeros. */
        private fun rounded(value: Double, maxFraction: Int): Pair<String, String> {
            val scale = tenTo(maxFraction)
            val scaled = value * scale
            if (scaled >= EXACT_LIMIT) return plainWhole(value) to ""
            val low = floor(scaled)
            val rest = scaled - low
            val units = when {
                rest > HALF -> low + 1
                rest < HALF -> low
                low % 2 == 0.0 -> low
                else -> low + 1
            }.toLong()
            val unitScale = scale.toLong()
            val fraction = if (maxFraction == 0) "" else (units % unitScale).toString().padStart(maxFraction, '0').trimEnd('0')
            return (units / unitScale).toString() to fraction
        }

        private const val HALF = 0.5

        /** The integer digits of a large [value], from its shortest decimal form. */
        private fun plainWhole(value: Double): String {
            val text = value.toString()
            val exponentAt = text.indexOfFirst { it == 'E' || it == 'e' }
            if (exponentAt < 0) return text.substringBefore('.')
            val mantissa = text.substring(0, exponentAt)
            val exponent = text.substring(exponentAt + 1).toInt()
            val digits = mantissa.replace(".", "")
            val point = mantissa.indexOf('.').let { if (it < 0) mantissa.length else it } + exponent
            return if (point >= digits.length) digits + "0".repeat(point - digits.length) else digits.substring(0, point)
        }

        private fun parseCompactRow(row: String): Map<PluralCategory, CompactPattern>? {
            val forms = if ('|' in row) {
                row.split('|').associate { form ->
                    PluralCategory.ofKeyword(form.substringBefore('=')) as PluralCategory to form.substringAfter('=')
                }
            } else {
                mapOf(PluralCategory.Other to row)
            }
            val patterns = forms.mapValues { (_, pattern) -> splitPattern(pattern) }
            return if (patterns.values.all { it == null }) null else patterns.filterValues { it != null }.mapValues { it.value!! }
        }

        /** `0K` into "", 1, "K"; null for a pattern that is only zeros, which leaves a number uncompacted. */
        private fun splitPattern(pattern: String): CompactPattern? {
            val first = pattern.indexOf('0')
            if (first < 0) return null
            val last = pattern.lastIndexOf('0')
            val prefix = pattern.substring(0, first)
            val suffix = pattern.substring(last + 1)
            return if (prefix.isBlank() && suffix.isBlank()) null else CompactPattern(prefix, last - first + 1, suffix)
        }
    }
}
