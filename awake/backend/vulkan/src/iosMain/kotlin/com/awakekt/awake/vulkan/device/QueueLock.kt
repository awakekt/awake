package com.awakekt.awake.vulkan.device

import platform.Foundation.NSRecursiveLock

internal actual class QueueLock {
    private val lock = NSRecursiveLock()

    actual inline fun <T> withLock(action: () -> T): T {
        lock.lock()
        try {
            return action()
        } finally {
            lock.unlock()
        }
    }
}
