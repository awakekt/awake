package com.awakekt.awake.scene.binding.processor

import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.CodeBlock
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.ParameterizedTypeName.Companion.parameterizedBy
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.TypeSpec

/** Writes the binding object [plan] describes. */
internal fun writeBinding(plan: BindingPlan): FileSpec {
    val request = plan.request
    val saved = request.saved.className
    val live = request.live.className
    val enums = plan.fields.mapNotNull { it.conversion as? Conversion.EnumByName }.distinct()
    val type = TypeSpec.objectBuilder(request.binding)
        .addSuperinterface(Names.BINDING.parameterizedBy(live, saved))
        .addKdoc(
            "Binds [%T] to [%T] both ways: generated from the `@SceneBinding` on [%T], so edit that, not this.\n",
            saved,
            live,
            saved,
        )
        .addProperty(classProperty("componentClass", live))
        .addProperty(classProperty("schemaClass", saved))
        .apply { if (request.saved.serializable) addProperty(serializerProperty(saved)) }
        .addFunction(attachFunction(request))
        .addFunction(exportFunction(request))
        .addFunction(toLiveFunction(plan, enums))
        .addFunction(toSavedFunction(plan, enums))
        .apply {
            enums.forEachIndexed { index, enum ->
                addFunction(enumFunction("liveEnum$index", enum.saved, enum.live, enum.constants))
                addFunction(enumFunction("savedEnum$index", enum.live, enum.saved, enum.constants))
            }
        }
        .build()
    return FileSpec.builder(request.binding)
        .addFileComment("Generated by the Awake scene binding processor from %L. Do not edit.", saved.simpleName)
        .addType(type)
        .build()
}

private fun classProperty(name: String, type: ClassName) = PropertySpec.builder(name, Names.K_CLASS.parameterizedBy(type))
    .addModifiers(KModifier.OVERRIDE)
    .initializer("%T::class", type)
    .build()

private fun serializerProperty(saved: ClassName) = PropertySpec.builder("serializer", Names.SERIALIZER.parameterizedBy(saved))
    .addModifiers(KModifier.OVERRIDE)
    .initializer("%T.serializer()", saved)
    .build()

private fun attachFunction(request: BindingRequest) = FunSpec.builder("attachTyped")
    .addModifiers(KModifier.OVERRIDE)
    .addParameter("world", Names.WORLD)
    .addParameter("entity", Names.ENTITY)
    .addParameter("component", request.saved.className)
    .addParameter("context", Names.CONTEXT)
    .addStatement("val live = component.toComponent()")
    .addStatement("world.add(entity, live)")
    .apply {
        request.hooks?.takeIf { "afterAttach" in it }?.let { addStatement("%T.afterAttach(world, entity, component, live, context)", it.className) }
    }
    .build()

private fun exportFunction(request: BindingRequest): FunSpec {
    val builder = FunSpec.builder("export")
        .addModifiers(KModifier.OVERRIDE)
        .addParameter("world", Names.WORLD)
        .addParameter("entity", Names.ENTITY)
        .addParameter("component", request.live.className)
    val hooks = request.hooks?.takeIf { "beforeExport" in it }?.className
    return if (hooks == null) {
        builder.returns(request.saved.className).addStatement("return·component.toSceneComponent()").build()
    } else {
        builder.returns(request.saved.className.copy(nullable = true))
            .addStatement("return·%T.beforeExport(world, entity, component, component.toSceneComponent())", hooks)
            .build()
    }
}

private fun toLiveFunction(plan: BindingPlan, enums: List<Conversion.EnumByName>): FunSpec {
    val request = plan.request
    val builder = FunSpec.builder("toComponent")
        .receiver(request.saved.className)
        .returns(request.live.className)
        .addKdoc("This schema as its live [%T], through the declared mapping.\n", request.live.className)
    plan.whole?.let { whole ->
        builder.addStatement("val saved = this")
        builder.addStatement("val live = %L", value(whole.conversion, false, CodeBlock.of("saved.%N", whole.saved), toLive = true, enums))
        return builder.finish(request.hooks, "afterCopyToLive", "saved", CodeBlock.of("live"))
    }
    return if (plan.isObjectPair) {
        builder.finish(request.hooks, "afterCopyToLive", "this", CodeBlock.of("%T", request.live.className))
    } else {
        builder.addStatement("val saved = this")
        val arguments = plan.fields.filter { it.viaConstructor }.map { field ->
            CodeBlock.of("%N = %L", field.live, value(field, CodeBlock.of("saved.%N", field.saved), toLive = true, enums))
        }
        builder.addCode(construct("live", request.live.className, arguments))
        plan.fields.filterNot { it.viaConstructor }.forEach { field ->
            builder.addStatement("live.%N = %L", field.live, value(field, CodeBlock.of("saved.%N", field.saved), toLive = true, enums))
        }
        builder.finish(request.hooks, "afterCopyToLive", "saved", CodeBlock.of("live"))
    }
}

private fun toSavedFunction(plan: BindingPlan, enums: List<Conversion.EnumByName>): FunSpec {
    val request = plan.request
    val builder = FunSpec.builder("toSceneComponent")
        .receiver(request.live.className)
        .returns(request.saved.className)
        .addKdoc("This live component as a new [%T], through the declared mapping.\n", request.saved.className)
    plan.whole?.let { whole ->
        builder.addStatement("val live = this")
        val argument = CodeBlock.of("%N = %L", whole.saved, value(whole.conversion, false, CodeBlock.of("live"), toLive = false, enums))
        builder.addCode(construct("saved", request.saved.className, listOf(argument)))
        return builder.finish(request.hooks, "afterCopyToSaved", "live", CodeBlock.of("saved"))
    }
    return if (plan.isObjectPair) {
        builder.finish(request.hooks, "afterCopyToSaved", "this", CodeBlock.of("%T", request.saved.className))
    } else {
        builder.addStatement("val live = this")
        val arguments = plan.fields.map { field ->
            CodeBlock.of("%N = %L", field.saved, value(field, CodeBlock.of("live.%N", field.live), toLive = false, enums))
        }
        builder.addCode(construct("saved", request.saved.className, arguments))
        builder.finish(request.hooks, "afterCopyToSaved", "live", CodeBlock.of("saved"))
    }
}

/** Returns [result], passed with [input] through the copy hook [hook] when the binding has [hooks]. */
private fun FunSpec.Builder.finish(hooks: Hooks?, hook: String, input: String, result: CodeBlock): FunSpec =
    if (hooks == null || hook !in hooks) {
        addStatement("return·%L", result).build()
    } else {
        addStatement("return·%T.%L(%L, %L)", hooks.className, hook, input, result).build()
    }
