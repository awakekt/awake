package com.awakekt.awake.scene.binding.processor

import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.CodeBlock
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.MemberName
import com.squareup.kotlinpoet.ParameterizedTypeName.Companion.parameterizedBy
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.STAR
import com.squareup.kotlinpoet.TypeSpec

/** Writes the module's `SceneComponentModule` object, [registry], listing [entries] by binding name. */
internal fun writeRegistry(registry: ClassName, entries: List<RegistryEntry>): FileSpec {
    val sorted = entries.sortedBy { it.binding.canonicalName }
    val bindings = CodeBlock.builder().add("listOf(\n").indent()
    sorted.forEach { bindings.add("%T,\n", it.binding) }
    bindings.unindent().add(")")
    val serializers = CodeBlock.builder()
        .add("%T {\n", Names.SERIALIZERS_MODULE).indent()
        .add("%M(%T::class) {\n", POLYMORPHIC, Names.SCENE_COMPONENT).indent()
    sorted.mapNotNull { it.serializableSchema }.distinct().forEach { serializers.add("subclass(%T::class, %T.serializer())\n", it, it) }
    serializers.unindent().add("}\n").unindent().add("}")
    val type = TypeSpec.objectBuilder(registry)
        .addSuperinterface(Names.MODULE)
        .addKdoc(
            "The scene components this module provides: its generated `@SceneBinding`s and its `@RegisteredBinding`s.\n" +
                "Generated by the Awake scene binding processor; register it with `SceneComponentRegistry.register`.\n",
        )
        .addProperty(
            PropertySpec.builder("bindings", LIST.parameterizedBy(Names.BINDING.parameterizedBy(STAR, STAR)))
                .addModifiers(KModifier.OVERRIDE)
                .initializer(bindings.build())
                .build(),
        )
        .addProperty(
            PropertySpec.builder("serializersModule", Names.SERIALIZERS_MODULE)
                .addModifiers(KModifier.OVERRIDE)
                .initializer(serializers.build())
                .build(),
        )
        .build()
    return FileSpec.builder(registry)
        .addFileComment("Generated by the Awake scene binding processor. Do not edit.")
        .addType(type)
        .build()
}

private val LIST = ClassName("kotlin.collections", "List")
private val POLYMORPHIC = MemberName("kotlinx.serialization.modules", "polymorphic")
